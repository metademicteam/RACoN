"""Read-only Supabase schema introspection.

RACoN shares its Postgres schema with the Next.js console, so the desktop product must
never guess table or column names and must never issue DDL. This script only performs GET
requests and writes a Markdown description of what actually exists.

Credentials come from the environment (or ``.env``):

* ``SUPABASE_URL``
* ``SUPABASE_ACCESS_TOKEN`` — Management API token, preferred (returns generated TS types)
* ``SUPABASE_SECRET_KEY`` — used against the project's PostgREST OpenAPI document

Usage:
    python scripts/introspect_supabase.py --out docs/SUPABASE_SCHEMA.md
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path
from typing import Any

import httpx

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from racon.settings import load_dotenv  # noqa: E402

PROJECT_REF_PATTERN = re.compile(r"https://([a-z0-9]+)\.supabase\.co", re.IGNORECASE)


class IntrospectionError(RuntimeError):
    pass


def resolve() -> tuple[str, str, str]:
    """Return (project_url, access_token, secret_key) without logging any of them."""
    values = load_dotenv()
    url = os.environ.get("SUPABASE_URL") or values.get("SUPABASE_URL") or ""
    access = os.environ.get("SUPABASE_ACCESS_TOKEN") or values.get("SUPABASE_ACCESS_TOKEN") or ""
    secret = os.environ.get("SUPABASE_SECRET_KEY") or values.get("SUPABASE_SECRET_KEY") or ""
    if not url:
        raise IntrospectionError("SUPABASE_URL is not set")
    if not access and not secret:
        raise IntrospectionError(
            "Neither SUPABASE_ACCESS_TOKEN nor SUPABASE_SECRET_KEY is set. "
            "Introspection is a server-side operation."
        )
    return url.rstrip("/"), access, secret


def project_ref(url: str) -> str:
    match = PROJECT_REF_PATTERN.match(url)
    if not match:
        raise IntrospectionError(f"Could not derive a project ref from {url}")
    return match.group(1)


def fetch_typescript_types(url: str, access_token: str) -> str:
    """Preferred path: the Management API generates types from the live database."""
    ref = project_ref(url)
    endpoint = f"https://api.supabase.com/v1/projects/{ref}/types/typescript"
    with httpx.Client(timeout=60.0) as client:
        response = client.get(endpoint, headers={"Authorization": f"Bearer {access_token}"})
    if response.status_code != 200:
        raise IntrospectionError(
            f"Management API returned HTTP {response.status_code}: {response.text[:200]}"
        )
    return response.text


def fetch_openapi(url: str, secret_key: str) -> dict[str, Any]:
    """Fallback: the PostgREST OpenAPI document for this project."""
    with httpx.Client(timeout=60.0) as client:
        response = client.get(
            f"{url}/rest/v1/",
            headers={
                "apikey": secret_key,
                "Authorization": f"Bearer {secret_key}",
                "Accept": "application/openapi+json",
                "User-Agent": "RACoN-Schema-Introspector/1.0",
            },
        )
    if response.status_code != 200:
        raise IntrospectionError(
            f"PostgREST OpenAPI returned HTTP {response.status_code}: {response.text[:200]}"
        )
    return response.json()


def parse_typescript_types(source: str) -> dict[str, dict[str, str]]:
    """Extract ``{table: {column: type}}`` from Supabase's generated TS definitions."""
    tables: dict[str, dict[str, str]] = {}
    current: str | None = None
    for line in source.splitlines():
        row_match = re.match(r"^\s{6}(\w+): \{$", line)
        if row_match:
            current = row_match.group(1)
            tables.setdefault(current, {})
            continue
        if current is None:
            continue
        row_match = re.match(r"^\s{6}Row: \{$", line)
        if row_match:
            continue
        row_match = re.match(r"^\s{8}(\w+)\??: (.+)$", line)
        if row_match:
            tables[current][row_match.group(1)] = row_match.group(2).rstrip(";")
    return {name: cols for name, cols in tables.items() if cols}


def parse_openapi(spec: dict[str, Any]) -> dict[str, dict[str, str]]:
    tables: dict[str, dict[str, str]] = {}
    for name, definition in (spec.get("definitions") or {}).items():
        properties = definition.get("properties") or {}
        columns: dict[str, str] = {}
        for column, meta in properties.items():
            fmt = meta.get("format") or meta.get("type") or "unknown"
            columns[column] = str(fmt)
        if columns:
            tables[name] = columns
    return tables


def render(tables: dict[str, dict[str, str]], source: str) -> str:
    lines = [
        "# RACoN Supabase schema (read-only snapshot)",
        "",
        "> Generated by `scripts/introspect_supabase.py`. Do not edit by hand.",
        "> This schema is owned by `racon-console-web`. RACoN never runs DDL against it.",
        "",
        f"Source: {source}",
        f"Tables: {len(tables)}",
        "",
    ]
    for name in sorted(tables):
        lines.append(f"## `public.{name}`")
        lines.append("")
        lines.append("| Column | Type |")
        lines.append("| --- | --- |")
        for column in sorted(tables[name]):
            lines.append(f"| `{column}` | `{tables[name][column]}` |")
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Read-only Supabase schema introspection")
    parser.add_argument("--out", default="docs/SUPABASE_SCHEMA.md", help="Markdown output path")
    parser.add_argument("--json", default="", help="Optional JSON output path")
    args = parser.parse_args()

    url, access_token, secret_key = resolve()

    tables: dict[str, dict[str, str]] = {}
    source = ""
    if access_token:
        try:
            typescript = fetch_typescript_types(url, access_token)
            tables = parse_typescript_types(typescript)
            source = "Supabase Management API (generated TypeScript types)"
        except IntrospectionError as exc:
            print(f"[warn] {exc}", file=sys.stderr)

    if not tables and secret_key:
        spec = fetch_openapi(url, secret_key)
        tables = parse_openapi(spec)
        source = "PostgREST OpenAPI document"

    if not tables:
        print("Introspection produced no tables. Check credentials and RLS grants.", file=sys.stderr)
        return 1

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(render(tables, source), encoding="utf-8")
    print(f"Wrote {out_path} ({len(tables)} tables) from {source}")

    if args.json:
        Path(args.json).write_text(json.dumps(tables, indent=2, sort_keys=True), encoding="utf-8")
        print(f"Wrote {args.json}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
